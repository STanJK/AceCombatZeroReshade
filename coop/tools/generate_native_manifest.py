#!/usr/bin/env python3
"""Generate only observed hook candidates from the same-build evidence, not hook approval."""
import hashlib
import json
from pathlib import Path
root=Path(__file__).resolve().parents[2]
source=root/'docs/mp/HOOK_CANDIDATES.json'
data=json.loads(source.read_text())
rows={int(r['rva'],16):r for r in data['candidates']}
wanted=[(0x16e0b0,'enter'),(0x16e4c0,'leave'),(0x16e880,'campaign_update'),(0x16f550,'vs_update')]
lines=['// Generated by coop/tools/generate_native_manifest.py; static candidates only.',
       '// Source SHA256: '+hashlib.sha256(source.read_bytes()).hexdigest(),
       'pub const HOOKS: &[HookSpec] = &[']
for rva,name in wanted:
 row=rows[rva];raw=bytes.fromhex(row['first_32_file_bytes'])
 assert len(raw)==32
 lines.append(f'    HookSpec {{ name: "{name}", rva: 0x{rva:x}, bytes: [{", ".join(f"0x{x:02x}" for x in raw)}] }},')
lines.append('];')
(root/'coop/crates/game/src/build_manifest.rs').write_text('\n'.join(lines)+'\n')
